package com.automatethethings.xkey.oath

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Manages encryption and decryption of OATH shared secrets at rest
 * using an AES-256-GCM key stored in Android Keystore.
 *
 * On first use, an AES-256 key is generated in the hardware-backed
 * Android Keystore under the alias [KEY_ALIAS]. All subsequent calls
 * to [encryptSecret] and [decryptSecret] use this key for
 * authenticated encryption.
 *
 * Ciphertext format:
 * ```
 * [IV: 12 bytes][ciphertext + GCM authentication tag]
 * ```
 *
 * The 12-byte initialization vector (IV) is generated by the Android
 * Keystore provider during encryption and prepended to the output.
 * During decryption, the first 12 bytes are extracted as the IV and
 * the remainder is decrypted with GCM tag verification.
 *
 * Usage:
 * ```kotlin
 * val manager = OathSecretManager()
 *
 * val encrypted = manager.encryptSecret(totpSecret)
 * // Store encrypted in database...
 *
 * val decrypted = manager.decryptSecret(encrypted)
 * // Use decrypted secret for OTP generation...
 * ```
 */
class OathSecretManager {

    companion object {
        /** Android Keystore provider name. */
        private const val KEYSTORE_PROVIDER = "AndroidKeyStore"

        /** Alias for the OATH secret encryption key in Android Keystore. */
        private const val KEY_ALIAS = "xkey_oath_secret_encryption_key"

        /** AES-GCM cipher transformation string. */
        private const val AES_GCM_TRANSFORMATION = "AES/GCM/NoPadding"

        /** GCM initialization vector size in bytes. */
        private const val GCM_IV_SIZE = 12

        /** GCM authentication tag length in bits. */
        private const val GCM_TAG_LENGTH_BITS = 128

        /** AES key size in bits. */
        private const val AES_KEY_SIZE_BITS = 256
    }

    private val keyStore: KeyStore = KeyStore.getInstance(KEYSTORE_PROVIDER).apply {
        load(null)
    }

    /**
     * Encrypt an OATH shared secret for storage at rest.
     *
     * The Android Keystore provider generates a random 12-byte IV
     * internally. The output is the IV prepended to the AES-GCM
     * ciphertext (which includes the 128-bit authentication tag).
     *
     * @param plaintext The raw OATH secret bytes to encrypt.
     * @return Encrypted payload: IV (12 bytes) || ciphertext || GCM tag.
     * @throws java.security.GeneralSecurityException if encryption fails.
     */
    fun encryptSecret(plaintext: ByteArray): ByteArray {
        val key = getOrCreateKey()

        val cipher = Cipher.getInstance(AES_GCM_TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, key)

        val iv = cipher.iv
        val ciphertext = cipher.doFinal(plaintext)

        // Prepend IV to ciphertext
        return iv + ciphertext
    }

    /**
     * Decrypt an OATH shared secret from its encrypted storage form.
     *
     * Extracts the 12-byte IV from the beginning of [encrypted] and
     * uses it to initialize AES-GCM decryption. The GCM authentication
     * tag is verified automatically; an [javax.crypto.AEADBadTagException]
     * is thrown if the ciphertext has been tampered with.
     *
     * @param encrypted Encrypted payload produced by [encryptSecret]:
     *                  IV (12 bytes) || ciphertext || GCM tag.
     * @return The original plaintext OATH secret bytes.
     * @throws IllegalArgumentException if [encrypted] is shorter than
     *         the minimum size (IV + at least 1 byte of ciphertext).
     * @throws javax.crypto.AEADBadTagException if the authentication
     *         tag verification fails (data integrity violation).
     * @throws java.security.GeneralSecurityException if decryption fails.
     */
    fun decryptSecret(encrypted: ByteArray): ByteArray {
        require(encrypted.size > GCM_IV_SIZE) {
            "Encrypted data too short: must be at least ${GCM_IV_SIZE + 1} bytes, got ${encrypted.size}"
        }

        val key = getOrCreateKey()

        val iv = encrypted.copyOfRange(0, GCM_IV_SIZE)
        val ciphertext = encrypted.copyOfRange(GCM_IV_SIZE, encrypted.size)

        val cipher = Cipher.getInstance(AES_GCM_TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, key, GCMParameterSpec(GCM_TAG_LENGTH_BITS, iv))

        return cipher.doFinal(ciphertext)
    }

    /**
     * Retrieve the existing AES-256-GCM key from Android Keystore,
     * or generate a new one if it does not yet exist.
     *
     * The key is created with:
     * - [KeyProperties.PURPOSE_ENCRYPT] | [KeyProperties.PURPOSE_DECRYPT]
     * - [KeyProperties.BLOCK_MODE_GCM]
     * - [KeyProperties.ENCRYPTION_PADDING_NONE]
     * - 256-bit key size
     *
     * No user authentication is required for this key because it is
     * used programmatically during OATH secret storage and retrieval
     * operations that are already gated by app-level authentication.
     *
     * @return The AES [SecretKey] from Android Keystore.
     */
    private fun getOrCreateKey(): SecretKey {
        // Return existing key if present
        val existingKey = keyStore.getKey(KEY_ALIAS, null) as? SecretKey
        if (existingKey != null) {
            return existingKey
        }

        // Generate new AES-256 key in Android Keystore
        val keyGenSpec = KeyGenParameterSpec.Builder(
            KEY_ALIAS,
            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
        )
            .setKeySize(AES_KEY_SIZE_BITS)
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .build()

        val keyGenerator = KeyGenerator.getInstance(
            KeyProperties.KEY_ALGORITHM_AES,
            KEYSTORE_PROVIDER
        )
        keyGenerator.init(keyGenSpec)

        return keyGenerator.generateKey()
    }
}

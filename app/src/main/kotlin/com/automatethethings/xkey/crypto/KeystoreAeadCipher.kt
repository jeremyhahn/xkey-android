package com.automatethethings.xkey.crypto

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Generic AES-256-GCM encryption backed by a hardware-backed Android Keystore key.
 *
 * Each instance is bound to a distinct Keystore key [alias], generated on first
 * use. This is the shared at-rest encryption primitive for the app's secret
 * stores (OATH secrets, passwords); use a unique alias per store so key material
 * stays separated.
 *
 * Ciphertext format:
 * ```
 * [IV: 12 bytes][ciphertext + 128-bit GCM authentication tag]
 * ```
 *
 * The 12-byte IV is generated by the Keystore provider during encryption and
 * prepended to the output; on decryption it is split back off and the GCM tag is
 * verified automatically.
 */
class KeystoreAeadCipher(private val alias: String) {

    companion object {
        private const val KEYSTORE_PROVIDER = "AndroidKeyStore"
        private const val AES_GCM_TRANSFORMATION = "AES/GCM/NoPadding"
        private const val GCM_IV_SIZE = 12
        private const val GCM_TAG_LENGTH_BITS = 128
        private const val AES_KEY_SIZE_BITS = 256
    }

    private val keyStore: KeyStore = KeyStore.getInstance(KEYSTORE_PROVIDER).apply { load(null) }

    /**
     * Encrypt [plaintext]. Returns IV (12 bytes) || ciphertext || GCM tag.
     *
     * @throws java.security.GeneralSecurityException if encryption fails.
     */
    fun encrypt(plaintext: ByteArray): ByteArray {
        val cipher = Cipher.getInstance(AES_GCM_TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, getOrCreateKey())
        return cipher.iv + cipher.doFinal(plaintext)
    }

    /**
     * Decrypt data produced by [encrypt].
     *
     * @throws IllegalArgumentException if [encrypted] is shorter than the minimum size.
     * @throws javax.crypto.AEADBadTagException if the authentication tag fails (tampering).
     */
    fun decrypt(encrypted: ByteArray): ByteArray {
        require(encrypted.size > GCM_IV_SIZE) {
            "Encrypted data too short: must be at least ${GCM_IV_SIZE + 1} bytes, got ${encrypted.size}"
        }
        val iv = encrypted.copyOfRange(0, GCM_IV_SIZE)
        val ciphertext = encrypted.copyOfRange(GCM_IV_SIZE, encrypted.size)
        val cipher = Cipher.getInstance(AES_GCM_TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, getOrCreateKey(), GCMParameterSpec(GCM_TAG_LENGTH_BITS, iv))
        return cipher.doFinal(ciphertext)
    }

    private fun getOrCreateKey(): SecretKey {
        (keyStore.getKey(alias, null) as? SecretKey)?.let { return it }

        val spec = KeyGenParameterSpec.Builder(
            alias,
            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT
        )
            .setKeySize(AES_KEY_SIZE_BITS)
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .build()

        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, KEYSTORE_PROVIDER)
        generator.init(spec)
        return generator.generateKey()
    }
}
